// Which model feeds which tool: a data source at the top, the tools that
// build a model from it, the two kinds of model, and the User Console
// tool that reads each one, with Dashboard Designer showing them both
// and an Interactive Report going one way into Report Designer. It sits
// at the start of "The tools you will use" in 03-user-console/guide.md,
// before the tabs that describe each tool, with a "Read the diagram"
// paragraph after it.
//
// Every fact comes from the course's own lessons:
//   - Lesson 09 (09-analyzer-reports): a data source is relational
//     database tables or a CSV file, provided by an administrator or a
//     user with create data source permission. The data source for an
//     Analyzer report is based on a Mondrian schema (an Analysis Model):
//     an XML model with cube-like structures, created with Schema
//     Workbench or generated by the Data Source Wizard (a manually
//     entered SQL query, an auto-query, or a CSV file).
//   - Lesson 05 (05-interactive-reports): the data source for an
//     Interactive Report is based on a metadata model, which presents the
//     data in business terms. A metadata model is created with Pentaho
//     Metadata Editor or generated by the Data Source Wizard (a manually
//     entered SQL query, an auto-query, or a CSV file). Interactive
//     Reports are saved as .prpti files, Report Designer reports as
//     .prpt. Reports created in Interactive Reporting can be opened in
//     Report Designer; once customized there, they can no longer be
//     edited in Interactive Reporting.
//   - Lesson 03 (03-user-console), the architecture figure: Metadata
//     Editor's model travels to the server as .xmi, Schema Workbench's
//     as .mondrian.xml; Report Designer is a desktop tool, Analyzer,
//     Interactive Reports and Dashboard Designer are web-based.
//   - Lessons 05, 09 and 12: Interactive Reports and Analyzer reports
//     can be displayed in a dashboard. Lesson 13, "Dashboard Content":
//     reports created with Interactive Reporting, Analyzer and Report
//     Designer are added to dashboard panels.
//   - Lessons 13 and 15: Dashboard Designer's prompts (Metadata List) and
//     Chart Designer charts query the Orders metadata model directly
//     (the dashed arrow).
//
// Colors: blue the data source and the tools that build or design
// (Metadata Editor, Data Source Wizard, Schema Workbench, Report
// Designer), teal the two models, amber the web-based User Console
// tools that read them. Icons as in this folder's README.
//
// Run from this folder:   node models-and-tools.svg.mjs
// It writes models-and-tools.svg here and ../images/models-and-tools.png
// at twice the size.
import { Diagram } from '../../../../scripts/diagram-kit.mjs';

// Canvas and grid: 800 wide, three columns of same-size boxes (BW x BH)
// with 36px between columns, and 48px between rows for the arrows and
// their pills.
const W = 800, BW = 232, BH = 72;
const COL = [16, 284, 552]; // left edge of each column
const ROW = [126, 246, 366, 486]; // top of each box row under the bar
const d = new Diagram(W, ROW[3] + BH + 16);

// A box in column `c`, row `r`.
const cell = (c, r, o) => d.box({ x: COL[c], y: ROW[r], w: BW, h: BH, ...o });

// ── Row 0: the data source, a full-width bar ──────────────────────────
// Blue: a source. Every model starts from it.
const src = d.bar({ x: 16, y: 16, w: W - 32, h: 62, role: 'source', iconName: 'database', title: 'A data source', line: 'relational database tables or a CSV file, provided by an administrator' });

// ── Row 1: the tools that build a model ───────────────────────────────
// Blue: tools you use. The Data Source Wizard sits in the middle
// because it can generate either kind of model.
const me = cell(0, 0, { role: 'tool', iconName: 'layers', title: 'Metadata Editor', lines: ['builds a metadata model'] });
const dsw = cell(1, 0, { role: 'tool', iconName: 'wand-sparkles', title: 'Data Source Wizard', lines: ['SQL query, auto-query', 'or CSV file'] });
const swb = cell(2, 0, { role: 'tool', iconName: 'box', title: 'Schema Workbench', lines: ['builds a Mondrian schema'] });

// Each builder reads the data source: a straight arrow down from the
// bar to the top of each box.
for (const b of [me, dsw, swb]) d.arrow({ x1: b.cx, y1: src.b, x2: b.cx, y2: b.y - 3, straight: true });

// ── Row 2: the two models ─────────────────────────────────────────────
// Teal: models. Metadata model under its editor, Mondrian schema under
// its workbench; the middle column is left free for the wizard's arrows
// and the dashboard's dashed arrow.
const mm = cell(0, 1, { role: 'model', iconName: 'shapes', title: 'Metadata model', lines: ['business terms;', 'saved as .xmi'] });
const ms = cell(2, 1, { role: 'model', iconName: 'file-code', title: 'Mondrian schema', lines: ['cube-like XML; saved', 'as .mondrian.xml'] });

// Each editor builds its own model: straight down.
d.arrow({ x1: me.cx, y1: me.b, x2: mm.cx, y2: mm.y - 3, straight: true });
d.arrow({ x1: swb.cx, y1: swb.b, x2: ms.cx, y2: ms.y - 3, straight: true });
// The wizard generates either: two curves from its foot down into the
// top of each model, with one pill between them.
d.arrow({ x1: dsw.cx - 40, y1: dsw.b, x2: mm.r - 40, y2: mm.y - 3, vertical: true });
d.arrow({ x1: dsw.cx + 40, y1: dsw.b, x2: ms.x + 40, y2: ms.y - 3, vertical: true });
d.pill(dsw.cx, (dsw.b + mm.y) / 2, 'generates either');

// ── Row 3: the User Console tools that read each model ────────────────
// Amber: web-based tools in the browser. Interactive Reports reads the
// metadata model, Analyzer the Mondrian schema, and Dashboard Designer
// sits between them because its panels show both.
const ir = cell(0, 2, { role: 'browser', iconName: 'file-text', title: 'Interactive Reports', lines: ['web-based; reports', 'saved as .prpti'] });
const dd = cell(1, 2, { role: 'browser', iconName: 'layout-dashboard', title: 'Dashboard Designer', lines: ['its panels show reports', 'from each of these tools'] });
const an = cell(2, 2, { role: 'browser', iconName: 'chart-column', title: 'Analyzer', lines: ['drill, slice, pivot', 'and filter the data'] });

// Each model feeds its tool: straight down.
d.arrow({ x1: mm.cx, y1: mm.b, x2: ir.cx, y2: ir.y - 3, straight: true });
d.arrow({ x1: ms.cx, y1: ms.b, x2: an.cx, y2: an.y - 3, straight: true });
// Both reports go into dashboard panels: short straight arrows into
// Dashboard Designer's two sides.
d.arrow({ x1: ir.r, y1: ir.cy, x2: dd.x - 3, y2: dd.cy, straight: true });
d.arrow({ x1: an.x, y1: an.cy, x2: dd.r + 3, y2: dd.cy, straight: true });
// Dashboard Designer's own prompts and charts query the metadata model
// directly: a dashed elbow from the model's right edge across the free
// middle cell and down into the top of Dashboard Designer.
d.arrow({ x1: mm.r, y1: mm.cy, x2: dd.cx, y2: dd.y - 3, elbow: true, dashed: true });
d.pill(dd.cx, mm.cy + 26, 'prompts and charts');

// ── Row 4: Report Designer, one way from an Interactive Report ────────
// Blue: a desktop tool you use. The Interactive Report opens in it and
// becomes a .prpt; nothing comes back the other way.
const rd = cell(0, 3, { role: 'tool', iconName: 'file-chart-column', title: 'Report Designer', lines: ['desktop tool; reports', 'saved as .prpt'] });
d.arrow({ x1: ir.cx, y1: ir.b, x2: rd.cx, y2: rd.y - 3, straight: true, label: 'opened in Report Designer as .prpt' });
// Report Designer reports go into dashboard panels too: an elbow from
// its right edge up into the foot of Dashboard Designer.
d.arrow({ x1: rd.r, y1: rd.cy, x2: dd.cx, y2: dd.b + 3, elbow: true });
// The one-way rule, as a note in the free cell at the bottom right.
d.pill(COL[2] + BW / 2, rd.cy, ['One way: once customized', 'in Report Designer, it can no', 'longer be edited in', 'Interactive Reports']);

d.write(import.meta.url);
